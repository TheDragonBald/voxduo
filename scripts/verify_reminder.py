"""Напоминания о ритуалах проекта на разных моментах git/gh-команд.

Запускается хуком PreToolUse на инструментах Bash и PowerShell — на Windows
это два разных пути к одной и той же команде, и покрывать надо оба. Смотрит
на команду и подбирает напоминание под конкретный момент: начало ветки,
коммит, создание PR или его мерж. У каждого момента свой текст — общего
"на всё" больше нет, потому что общий текст читался вскользь и терялся между
разными по смыслу шагами.

Зачем именно хук, а не строчка в документе: правило в рабочих заметках
проекта читается один раз в начале сессии, а нужно оно в конкретный момент — когда рука уже
тянется сказать «готово». Тот же приём, что и со снимком перед сжатием:
лечим не память, а процедуру.

Молчит на всех остальных командах и никогда не блокирует вызов: при любой
неожиданности выходит с нулевым кодом и пустым выводом.

Проверить вручную:
    echo '{"tool_input":{"command":"git commit -m x"}}' | uv run --frozen --no-sync python scripts/verify_reminder.py
"""

from __future__ import annotations

import json
import re
import sys

# Общий фрагмент для всех паттернов на `git`: пропустить глобальные флаги
# между `git` и подкомандой — `-C <путь>`, `--no-pager`, `--git-dir=<путь>`.
# Это не теория — инструмент оболочки прямо советует не пользоваться `cd`, и
# естественная замена как раз `git -C`.
_GIT_FLAGS = r"(?:\s+(?:-[A-Za-z]\s+\S+|--?[\w-]+(?:=\S+)?))*"

# Начало этапа: новая ветка. `git switch -c <имя>` и старый `git checkout -b
# <имя>` — оба в ходу, второй у части команд ещё не сменился на первый.
BRANCH_START = re.compile(rf"\bgit\b{_GIT_FLAGS}\s+(?:switch\s+-c|checkout\s+-b)\b")

# Коммит. Регулярка не менялась с версии, где ловились `git -C <путь> commit`
# и `git --no-pager commit`, — три бага стоило найти это правило, трогать не надо.
COMMIT = re.compile(rf"\bgit\b{_GIT_FLAGS}\s+commit\b")

# Создание и мерж PR — разные моменты с разными напоминаниями, поэтому больше
# не объединены в один паттерн.
PR_CREATE = re.compile(r"\bgh\s+pr\s+create\b")
PR_MERGE = re.compile(r"\bgh\s+pr\s+merge\b")

# Исторический паттерн: сумма COMMIT / PR_CREATE / PR_MERGE, как было до
# разделения на моменты. В логике хука больше не участвует — выбор текста
# идёт по MOMENTS ниже, — но остаётся как есть, потому что его напрямую
# проверяют старые тесты (границы на `git -C`, `--no-pager`, `git commitx` и
# так далее), и переносить эти проверки на новые паттерны без нужды незачем.
TRIGGERS = re.compile(f"{COMMIT.pattern}|{PR_CREATE.pattern}|{PR_MERGE.pattern}")

REMINDER_BRANCH_START = (
    "Начинается этап. Новая функциональность — сначала `brainstorming`, до "
    "единой строки кода. План уже есть — `subagent-driven-development` на "
    "исполнение. Внутри каждой задачи — `test-driven-development`: падающий "
    "тест первым."
)

REMINDER_COMMIT = (
    "Ритуал проекта: verification-before-completion. "
    "Слова «готово», «работает», «проходит», «зелено» допустимы только со "
    "свежим выводом команды в этом же сообщении. Если `just all` в этот раз "
    "не запускался — запустить и показать вывод, а не пересказать. "
    "Вывод прошлого прогона доказательством не является: код мог измениться "
    "после него. Зелёный pre-commit — тоже не доказательство: нужен свежий "
    "вывод `just all`."
)

REMINDER_PR_CREATE = (
    "Ритуал проекта: requesting-code-review. Ревьюер получает "
    "сконструированный контекст, а не историю этой сессии — описание PR "
    "должно быть понятно и без неё. Доказательства нужны те же, что и для "
    "коммита: свежий вывод `just all` в этом сообщении, а не пересказ "
    "прошлого прогона."
)

REMINDER_PR_MERGE = (
    "Этап закрывается. Проверить по списку: идеи вне скоупа — в IDEAS.md и "
    "issue, с поиском дубликатов перед созданием; выполненные пункты — "
    "чекбоксами в PLAN.md; журнал решений и выученные уроки — в CLAUDE.md; "
    "запись об изменении — в CHANGELOG.md."
)

# Порядок задан явно — от начала этапа к его закрытию, а не как лягут
# словари. В одной команде может встретиться два триггера сразу
# (`git switch -c x && git commit`), и без явного порядка результат был бы
# случайным. Первый совпавший по этому списку и выигрывает.
MOMENTS: list[tuple[re.Pattern[str], str]] = [
    (BRANCH_START, REMINDER_BRANCH_START),
    (COMMIT, REMINDER_COMMIT),
    (PR_CREATE, REMINDER_PR_CREATE),
    (PR_MERGE, REMINDER_PR_MERGE),
]


def main() -> int:
    # Ловим всё подряд намеренно: хук висит на каждом вызове оболочки, и
    # трейсбек из-за неожиданного входа замусорит транскрипт на ровном месте.
    # Заблокировать вызов он всё равно не может — для этого нужен код 2.
    try:
        payload = json.load(sys.stdin)
    except Exception:
        return 0

    command = ""
    if isinstance(payload, dict):
        tool_input = payload.get("tool_input")
        if isinstance(tool_input, dict):
            raw = tool_input.get("command")
            # Именно проверка типа, а не str(): str() от словаря содержит его
            # содержимое, и {"command": {"a": "git commit"}} дал бы напоминание
            if isinstance(raw, str):
                command = raw

    # Первый совпавший по порядку MOMENTS и выигрывает — см. комментарий там же.
    reminder = next((text for pattern, text in MOMENTS if pattern.search(command)), None)
    if reminder is None:
        return 0

    # ensure_ascii=True (по умолчанию) здесь принципиально: вывод уходит в
    # канал, а не в файл, и Python кодирует его локальной кодировкой — на этой
    # машине cp1251, отчего кириллица приезжает мусором (проверено:
    # `print('привет')` через канал даёт EF F0 E8 E2 E5 F2, невалидный UTF-8).
    # Экранирование \uXXXX — валидный JSON в любой кодировке, поэтому вопрос
    # снимается целиком, а не лечится подбором reconfigure().
    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "additionalContext": reminder,
                }
            }
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
